<#
.SYNOPSIS
    Register the Postgres-Dump-Daily scheduled task and regenerate its hidden launcher VBS.

.DESCRIPTION
    Creates/updates a daily task at 03:33 (StartWhenAvailable: a missed start
    fires on wake — proven 2026-10-30) that runs backup-pgdump.ps1 to dump the
    unified_store to TWO destinations:
      - GDrive offsite : G:\Mon Drive\Backups-Cloud   (DriveFS, per-user mount)
      - USB local leg  : F:\Backups\postgres-backups  (SanDisk Desk SSD 7.4 TB)
    plus a poison-guard floor (-MinRows 15000; the DB held ~16.5k conversations
    on 2026-10-31 — the old task ran with MinRows=0, i.e. an inert guard).

    The task action is the hidden launcher VBS (no console flash), same pattern
    as the fleet's claude-hidden-launchers — regenerated BY THIS SCRIPT, never
    hand-edited. The VBS is written FIRST (fail fast) so an access-denied on
    ProgramData aborts before the task is touched.

    Try WITHOUT elevation first (the task runs as the interactive user, so
    non-elevated registration may succeed). If access is denied, run elevated:
      pwsh -File D:\postgres\myia_postgres\scripts\setup-backup-schtasks.ps1

.NOTES
    Single UAC gesture per lane (UAC discipline): this is the only elevated
    action the postgres lane requires. Refs: roo-extensions #2553 / EPIC #2191.
#>
$ErrorActionPreference = 'Stop'

$taskName = 'Postgres-Dump-Daily'
$script   = 'D:\postgres\myia_postgres\scripts\backup-pgdump.ps1'
$shared   = 'G:\Mon Drive\Backups-Cloud'
$localDir = 'F:\Backups\postgres-backups'   # USB Desk SSD — 2026-10-31: GDrive was a single point of failure (day 30/10 lost)
$minRows  = 15000
$vbsPath  = 'C:\ProgramData\claude-hidden-launchers\Postgres-Dump-Daily.vbs'

# ========== PRE-FLIGHT (fail fast, BEFORE touching anything) ==========
if (-not (Test-Path $script)) { throw "backup script not found: $script" }
if (-not (Test-Path 'F:\')) {
    Write-Warning 'F: (USB Desk SSD) not mounted: the local leg will fail (exit 3, GDrive-only) until the disk is back.'
}
if (-not (Test-Path $shared)) {
    Write-Warning "GDrive offsite root not visible right now ($shared) — the task itself waits on DriveFS at run time."
}

# ========== 1. REGENERATE THE HIDDEN LAUNCHER VBS ==========
$pwshArgs = "-NoProfile -ExecutionPolicy Bypass -File `"$script`" -LocalCopyDir `"$localDir`" -SharedPath `"$shared`" -MinRows $minRows"
$vbsInner = $pwshArgs.Replace('"', '""')   # VBS doubles quotes inside a string literal
$vbsLines = @(
    "' Genere par D:\postgres\myia_postgres\scripts\setup-backup-schtasks.ps1 -- NE PAS EDITER A LA MAIN.",
    "' Tache      : $taskName",
    "' Objet      : lancer la commande sans jamais afficher de console.",
    "' Mecanisme  : Run(cmd, 0, True) passe SW_HIDE dans le STARTUPINFO du CreateProcess, donc",
    "'              conhost n'est jamais affiche -- contrairement a -WindowStyle Hidden, applique",
    "'              seulement APRES que PowerShell ait alloue et montre sa console (le `"flash`").",
    'Option Explicit',
    'Dim sh, rc',
    'Set sh = CreateObject("WScript.Shell")',
    'rc = sh.Run("pwsh.exe ' + $vbsInner + '", 0, True)',
    'WScript.Quit rc'
)
$vbsDir = Split-Path $vbsPath
if (-not (Test-Path $vbsDir)) { New-Item -ItemType Directory -Path $vbsDir -Force | Out-Null }
[System.IO.File]::WriteAllText($vbsPath, ($vbsLines -join "`r`n") + "`r`n", [System.Text.UTF8Encoding]::new($false))
Write-Host "VBS regenerated: $vbsPath"
Write-Host "  args: $pwshArgs"

# ========== 2. (UN)REGISTER THE TASK ==========
$existing = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
if ($existing) {
    Unregister-ScheduledTask -TaskName $taskName -Confirm:$false
    Write-Host "Unregistered existing task: $taskName"
}

# Run as the logged-in user, NOT SYSTEM: the GDrive mount (G:) is per-user —
# under SYSTEM the offsite path does not exist and the backup silently degrades
# (incident 2026-06-12 03:33). Same principal as Qdrant-Snapshot-Daily (Interactive).
$user = "$env:USERDOMAIN\$env:USERNAME"
$action    = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument "//B //Nologo `"$vbsPath`""
$trigger   = New-ScheduledTaskTrigger -Daily -At '03:33'
$settings  = New-ScheduledTaskSettingsSet `
    -StartWhenAvailable `
    -DontStopIfGoingOnBatteries `
    -AllowStartIfOnBatteries `
    -ExecutionTimeLimit (New-TimeSpan -Hours 1)
$principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive

Register-ScheduledTask `
    -TaskName $taskName `
    -Action $action `
    -Trigger $trigger `
    -Settings $settings `
    -Principal $principal `
    -Description 'Daily pg_dump backup of unified_store (ai-01) to GDrive offsite + USB Desk SSD (F:) local leg, poison-guard MinRows 15000'

Write-Host "Registered: $taskName (daily 03:33, $user, Interactive)"
Write-Host "Destinations: offsite=$shared ; local=$localDir ; MinRows=$minRows"

# Verify with an instrument that sees the result (UAC discipline rule 3):
$schtasksOut = schtasks /query /tn $taskName 2>&1
Write-Host "--- verify ---"
$schtasksOut
